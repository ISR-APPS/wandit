/** The most people that the name lists can name with no repeat: 64 x 64. */
export const MAX_NAMED_PEOPLE = FIRST_NAMES.length * LAST_NAMES.length;

/**
 * The name of the person at `index` (0 to MAX_NAMED_PEOPLE - 1). Each index gives a different full name.
 * 64 people in a row have 64 different first names, so the people of one team do not share a first name.
 */
export function personNameAt(index: number): { first: string; last: string } {
	const firstIndex = index % FIRST_NAMES.length;
	const block = Math.floor(index / FIRST_NAMES.length);
	// For one first name, each block of 64 people gives another last name. The step of 5 mixes the last names of a team.
	const lastIndex = (block + firstIndex * 5) % LAST_NAMES.length;
	return {
		first: FIRST_NAMES[firstIndex] ?? "",
		last: LAST_NAMES[lastIndex] ?? "",
	};
}
