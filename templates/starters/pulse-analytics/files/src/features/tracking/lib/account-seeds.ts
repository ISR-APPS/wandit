// The 72 customer accounts of the sample tables: who they are, how large, how old, and how their use moves.
// Only sample-data.ts reads this file. It builds the people and the events of each account from these facts.
// Every company is fictional. The `.example` domain can never be a real mail domain.
import type { Plan, Region } from "./dimensions";

/** How the use of an account moves in the sample history. */
export type UseTrend =
	/** The same people stay active. */
	| "steady"
	/** New people join until yesterday. */
	| "growing"
	/** People stop one by one in the last weeks. */
	| "fading"
	/** Nobody is active in the last `quietDays` days. */
	| "gone";

/** The fixed facts of one account. */
export type AccountSeed = {
	name: string;
	/** The first label of the mail domain: "harborline" gives harborline.example. */
	domain: string;
	/** Free text, for example "Logistics". */
	industry: string;
	region: Region;
	plan: Plan;
	/** How many people the account has. */
	members: number;
	/** How many seats the plan holds. Never below `members`. */
	seats: number;
	/** The age of the account in days. 1 is yesterday. */
	createdDaysAgo: number;
	trend: UseTrend;
	/** Only for "gone": the count of days with no activity, yesterday included. */
	quietDays: number;
};

// One account in one line. The arguments follow the fields of AccountSeed.
function account(
	name: string,
	domain: string,
	industry: string,
	region: Region,
	plan: Plan,
	members: number,
	seats: number,
	createdDaysAgo: number,
	trend: UseTrend = "steady",
	quietDays = 0,
): AccountSeed {
	return {
		name,
		domain,
		industry,
		region,
		plan,
		members,
		seats,
		createdDaysAgo,
		trend,
		quietDays,
	};
}

