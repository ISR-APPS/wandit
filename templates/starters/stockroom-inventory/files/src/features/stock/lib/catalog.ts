// The fixed master data of the warehouse: the suppliers and the 60 stock items with their settings.
// sample-data.ts reads these lists and plays the stock history on top of them.
// All names, people, emails, and phone numbers are fictional. The emails use the reserved .example domain.

/** The six product families of the stockroom. Each family has its own aisle. */
export const STOCK_CATEGORIES = [
	"packaging",
	"fasteners",
	"safety",
	"cleaning",
	"electrical",
	"tools",
] as const;

/** One product family. Its label is the message key `categories.<category>`. */
export type StockCategory = (typeof STOCK_CATEGORIES)[number];

/** The unit that one item is stored and counted in. Its label is the message key `units.<unit>.one` or `.other`. */
export type StockUnit =
	| "each"
	| "box"
	| "roll"
	| "pack"
	| "pair"
	| "case"
	| "can"
	| "bag"
	| "jug"
	| "bottle"
	| "spool"
	| "set";

/** One supplier and the terms that the simulation uses. */
export type SupplierSpec = {
	id: string;
	name: string;
	/** The account manager at the supplier. */
	contactName: string;
	email: string;
	phone: string;
	city: string;
	/** Promised days from the order to the delivery. */
	leadTimeDays: number;
	/** The weekday of the weekly order run: 1 is Monday, 5 is Friday. */
	orderWeekday: number;
	/** The chance that a delivery comes on the expected day or earlier, from 0 to 1. */
	onTimeChance: number;
	/** The chance that a delivery comes in two parts, from 0 to 1. */
	splitChance: number;
};

/** One stock item before the simulation gives it a stock level. */
export type ItemSpec = {
	/** The stock keeping unit on the shelf label, for example "PKG-1001". Its lower case is the URL id. */
	sku: string;
	name: string;
	category: StockCategory;
	unit: StockUnit;
	/** Purchase price of one unit, in STOCK_CURRENCY. */
	unitCost: number;
	/** Units picked on an average Monday to Friday. Saturday picks are about a third, Sunday has none. */
	weekdayDemand: number;
	supplierId: string;
};

