// The fixed part of the Studio OS sample: the team, the clients, and the projects with their plans.
// sample-data.ts reads these lists and derives the time entries, the deliverables, and the invoices from them.
// Every name is fictional. Offsets count calendar days back from today, so the studio never looks old.
import type { BillingType, Industry, Role, Service } from "./codes";

/** One person of the studio. */
export type MemberSeed = {
	id: string;
	name: string;
	role: Role;
	/** Contract hours per week. 32 means four days. */
	weeklyCapacity: number;
};

/** One client company. */
export type ClientSeed = {
	id: string;
	name: string;
	industry: Industry;
	/** Member id of the account lead. */
	leadId: string;
	/** Days from invoice to payment, before the noise. Above 30 the client pays late. */
	paymentDelay: number;
};

/** The plan of one project. The generator turns it into hours, deliverables, and invoices. */
export type ProjectSeed = {
	id: string;
	name: string;
	clientId: string;
	service: Service;
	billing: BillingType;
	/** Days from the start of the project to today. */
	startedDaysAgo: number;
	/** Length of the project in days. null for a retainer, which runs until further notice. */
	durationDays: number | null;
	/** Fixed fee or hour cap in euros. For a retainer: the monthly fee. */
	budget: number;
	/** Blended hourly rate in euros. Hours times this rate give the spend. */
	rate: number;
	/** Member id of the project lead. Also the first member of `teamIds`. */
	leadId: string;
	teamIds: readonly string[];
	/** Hours worked against the plan: 1.2 means 20 % more hours than the budget pays for. */
	burn: number;
};

