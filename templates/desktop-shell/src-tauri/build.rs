//! Build script of the desktop shell (docs/v2/desktop-apps.md, section 5).
//! It reads `../migrations`, which the build input places next to `src-tauri/`, checks
//! each file name, and writes `OUT_DIR/migrations.rs` for `src/db.rs`. Then it runs
//! tauri-build, which makes the permissions of the 4 app commands.

use sha2::{Digest, Sha256};
use std::{env, fs, path::PathBuf};

/// The commands that the webview may call. tauri-build makes `allow-<command>` for each.
const APP_COMMANDS: &[&str] = &["db_select", "db_execute", "db_batch", "app_info"];

fn main() {
    // A panic stops the build and shows the message. CI must never ship a wrong file list.
    if let Err(message) = embed_migrations() {
        panic!("migrations: {message}");
    }
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(APP_COMMANDS)),
    )
    .expect("tauri-build failed");
}

/// One checked file of `../migrations`.
struct MigrationFile {
    version: u32,
    /// The name part of the file name, for example `add_customers`.
    name: String,
    /// Absolute path, given to `include_str!`.
    path: String,
    /// Lowercase hex SHA-256 of the exact file bytes.
    sha256: String,
}

fn embed_migrations() -> Result<(), String> {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").map_err(|error| error.to_string())?;
    let folder = PathBuf::from(manifest_dir).join("..").join("migrations");
    // Cargo scans a folder for changes, so a new, changed, or deleted file runs this again.
    println!("cargo:rerun-if-changed={}", folder.display());

    let entries = fs::read_dir(&folder)
        .map_err(|error| format!("cannot read {}: {error}", folder.display()))?;
    let mut files = Vec::new();
    for entry in entries {
        let entry = entry.map_err(|error| error.to_string())?;
        let file_name = entry
            .file_name()
            .into_string()
            .map_err(|name| format!("{name:?} is not a UTF-8 file name"))?;
        let (version, name) = parse_file_name(&file_name).ok_or_else(|| {
            format!("{file_name} does not match NNNN_snake_name.sql with a version above 0")
        })?;
        // `file_type` does not follow a symlink, so a link to another file fails here.
        let is_file = entry
            .file_type()
            .map_err(|error| error.to_string())?
            .is_file();
        if !is_file {
            return Err(format!("{file_name} is not a regular file"));
        }
        let path = entry.path();
        let bytes = fs::read(&path).map_err(|error| format!("cannot read {file_name}: {error}"))?;
        if std::str::from_utf8(&bytes).is_err() {
            return Err(format!("{file_name} is not UTF-8 text"));
        }
        let path = path
            .to_str()
            .ok_or_else(|| format!("the path of {file_name} is not UTF-8"))?
            .to_owned();
        files.push(MigrationFile {
            version,
            name: name.to_owned(),
            path,
            sha256: hex(&Sha256::digest(&bytes)),
        });
    }

    files.sort_by_key(|file| file.version);
    if let Some(pair) = files
        .windows(2)
        .find(|pair| pair[0].version == pair[1].version)
    {
        return Err(format!(
            "{:04}_{}.sql and {:04}_{}.sql have the same version",
            pair[0].version, pair[0].name, pair[1].version, pair[1].name
        ));
    }

    let mut code = String::from(
        "/// The SQL files of `migrations/`, sorted by version. Generated by build.rs.\n\
         pub static EMBEDDED_MIGRATIONS: &[Migration] = &[\n",
    );
    for file in &files {
        // `{:?}` writes a Rust string literal, with the backslashes of a Windows path escaped.
        code.push_str(&format!(
            "    Migration {{ version: {}, name: {:?}, sql: include_str!({:?}), sha256: {:?} }},\n",
            file.version, file.name, file.path, file.sha256
        ));
    }
    code.push_str("];\n");

    let out_dir = env::var("OUT_DIR").map_err(|error| error.to_string())?;
    let out_file = PathBuf::from(out_dir).join("migrations.rs");
    fs::write(&out_file, code)
        .map_err(|error| format!("cannot write {}: {error}", out_file.display()))
}

/// Reads `NNNN_name.sql`. The same rule as `DESKTOP_MIGRATION_FILE_PATTERN` in
/// packages/contracts/src/v2/desktop.ts: `^(\d{4})_([a-z][a-z0-9_]{0,59})\.sql$`, version above 0.
fn parse_file_name(file_name: &str) -> Option<(u32, &str)> {
    let stem = file_name.strip_suffix(".sql")?;
    // `split_at_checked` answers None when byte 4 is inside a non-ASCII character.
    let (digits, rest) = stem.split_at_checked(4)?;
    let name = rest.strip_prefix('_')?;
    if !digits.bytes().all(|byte| byte.is_ascii_digit()) {
        return None;
    }
    let starts_with_letter = name
        .bytes()
        .next()
        .is_some_and(|byte| byte.is_ascii_lowercase());
    let is_snake_case = name
        .bytes()
        .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'_');
    if !starts_with_letter || !is_snake_case || name.len() > 60 {
        return None;
    }
    let version: u32 = digits.parse().ok()?;
    (version > 0).then_some((version, name))
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}
